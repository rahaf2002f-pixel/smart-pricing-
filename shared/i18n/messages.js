const reverse = Object.fromEntries(Object.entries(apiEnglish).map(([ar, en]) => [en, ar]));
export function translateApiMessage(message, language = "ar") {
  if (typeof message !== "string") return message;
  const source = reverse[message] || message;
  const custom = source.match(/^يمكن إضافة حتى (\d+) بنود تكلفة\.$/);
  if (custom) return language === "en" ? `You can add up to ${custom[1]} cost items.` : source;
  const customEnglish = source.match(/^You can add up to (\d+) cost items\.$/);
  if (customEnglish) return language === "ar" ? `يمكن إضافة حتى ${customEnglish[1]} بنود تكلفة.` : source;
  return language === "en" ? apiEnglish[source] || source : source;
}
